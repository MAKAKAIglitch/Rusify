package dev.rusify.client;

import net.minecraft.client.Minecraft;
import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;

public final class TranslationPackManager {
    private static final String PACK_FOLDER = "Rusify-Translations";
    private static final String PACK_ID = "file/" + PACK_FOLDER;
    private static final String MARKER = ".rusify-pack";
    private static final String MARKER_CONTENT = "Generated by Rusify. Safe to regenerate.\n";
    private static final List<String> MODS = List.of("carryon", "offlinelan", "ali", "stonezone", "gemsrealm",
            "punchy", "sable", "tectonic", "expandeddelight", "screenshot_viewer", "ragdoll_reactions",
            "lendersdelight", "held_item_info");

    private TranslationPackManager() {}

    public static boolean isCarryOnEnabled() throws IOException { return isTranslationEnabled("carryon"); }
    public static boolean isOfflineLanEnabled() throws IOException { return isTranslationEnabled("offlinelan"); }
    public static boolean isAdvancedLootInfoEnabled() throws IOException { return isTranslationEnabled("ali"); }
    public static boolean isStoneZoneEnabled() throws IOException { return isTranslationEnabled("stonezone"); }
    public static boolean isGemsRealmEnabled() throws IOException { return isTranslationEnabled("gemsrealm"); }
    public static boolean isPunchyEnabled() throws IOException { return isTranslationEnabled("punchy"); }
    public static boolean isSableEnabled() throws IOException { return isTranslationEnabled("sable"); }
    public static boolean isExpandedDelightEnabled() throws IOException { return isTranslationEnabled("expandeddelight"); }
    public static boolean isScreenshotViewerEnabled() throws IOException { return isTranslationEnabled("screenshot_viewer"); }
    public static boolean isRagdollReactionsEnabled() throws IOException { return isTranslationEnabled("ragdoll_reactions"); }
    public static boolean isLendersDelightEnabled() throws IOException { return isTranslationEnabled("lendersdelight"); }
    public static boolean isHeldItemInfoEnabled() throws IOException { return isTranslationEnabled("held_item_info"); }

    public static boolean isTranslationEnabled(String modId) throws IOException {
        Translation translation = translation(modId);
        return Files.isRegularFile(translationFile(translation))
                && selectedPacks(Minecraft.getInstance()).contains(PACK_ID);
    }

    public static void setTranslationEnabled(String modId, boolean enabled) throws IOException {
        Translation translation = translation(modId);
        Minecraft minecraft = Minecraft.getInstance();
        Path pack = packDirectory();
        preparePack(pack);
        Path file = translationFile(translation);
        if (enabled) {
            Files.createDirectories(file.getParent());
            String resource = "/data/rusify/translations/" + translation.resourceFolder() + "/ru_ru.json";
            try (InputStream input = TranslationPackManager.class.getResourceAsStream(resource)) {
                if (input == null) throw new IOException("Встроенный перевод " + translation.name() + " не найден.");
                Files.copy(input, file, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            }
        } else {
            Files.deleteIfExists(file);
            removeEmptyParents(file.getParent(), pack);
        }

        List<String> selected = selectedPacks(minecraft);
        removeLegacyPacks(selected);
        if (hasAnyTranslation(pack)) {
            if (!selected.contains(PACK_ID)) selected.add(PACK_ID);
        } else {
            selected.removeIf(PACK_ID::equals);
            deleteOwnedPack(pack);
        }
        minecraft.options.save();
        minecraft.reloadResourcePacks();
    }

    public static void setCarryOnEnabled(boolean enabled) throws IOException { setTranslationEnabled("carryon", enabled); }
    public static void setOfflineLanEnabled(boolean enabled) throws IOException { setTranslationEnabled("offlinelan", enabled); }
    public static void setAdvancedLootInfoEnabled(boolean enabled) throws IOException { setTranslationEnabled("ali", enabled); }
    public static void setStoneZoneEnabled(boolean enabled) throws IOException { setTranslationEnabled("stonezone", enabled); }
    public static void setGemsRealmEnabled(boolean enabled) throws IOException { setTranslationEnabled("gemsrealm", enabled); }
    public static void setPunchyEnabled(boolean enabled) throws IOException { setTranslationEnabled("punchy", enabled); }
    public static void setSableEnabled(boolean enabled) throws IOException { setTranslationEnabled("sable", enabled); }
    public static void setExpandedDelightEnabled(boolean enabled) throws IOException { setTranslationEnabled("expandeddelight", enabled); }
    public static void setScreenshotViewerEnabled(boolean enabled) throws IOException { setTranslationEnabled("screenshot_viewer", enabled); }
    public static void setHeldItemInfoEnabled(boolean enabled) throws IOException { setTranslationEnabled("held_item_info", enabled); }

    public static void ensureDynamicPackEnabled() throws IOException {
        Minecraft minecraft = Minecraft.getInstance();
        List<String> selected = selectedPacks(minecraft);
        removeLegacyPacks(selected);
        Path pack = packDirectory();
        if (hasAnyTranslation(pack)) {
            verifyOwnedPack(pack);
            if (!selected.contains(PACK_ID)) selected.add(PACK_ID);
        } else {
            selected.removeIf(PACK_ID::equals);
            deleteOwnedPack(pack);
        }
        minecraft.options.save();
        minecraft.reloadResourcePacks();
    }

    public static void setAllBuiltInTranslationsEnabled(boolean enabled) throws IOException {
        for (String modId : MODS) {
            Translation translation = translation(modId);
            Path file = translationFile(translation);
            if (enabled) {
                Path pack = packDirectory();
                preparePack(pack);
                Files.createDirectories(file.getParent());
                String resource = "/data/rusify/translations/" + translation.resourceFolder() + "/ru_ru.json";
                try (InputStream input = TranslationPackManager.class.getResourceAsStream(resource)) {
                    if (input == null) throw new IOException("Не найден перевод " + translation.name());
                    Files.copy(input, file, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                }
            } else {
                Files.deleteIfExists(file);
                removeEmptyParents(file.getParent(), packDirectory());
            }
        }
        Minecraft minecraft = Minecraft.getInstance();
        List<String> selected = selectedPacks(minecraft);
        removeLegacyPacks(selected);
        Path pack = packDirectory();
        if (enabled && hasAnyTranslation(pack)) {
            preparePack(pack);
            if (!selected.contains(PACK_ID)) selected.add(PACK_ID);
        } else {
            selected.removeIf(PACK_ID::equals);
            deleteOwnedPack(pack);
        }
        minecraft.options.save();
        minecraft.reloadResourcePacks();
    }

    private static Translation translation(String modId) throws IOException {
        return switch (modId) {
            case "carryon" -> new Translation("Carry On", "carryon");
            case "offlinelan" -> new Translation("OfflineLAN", "offlinelan");
            case "ali" -> new Translation("Advanced Loot Info", "ali");
            case "stonezone" -> new Translation("Stone Zone", "stonezone");
            case "gemsrealm" -> new Translation("Gems Realm", "gemsrealm");
            case "punchy" -> new Translation("Punchy!", "punchy");
            case "sable" -> new Translation("Sable", "sable");
            case "tectonic" -> new Translation("Tectonic", "tectonic");
            case "expandeddelight" -> new Translation("Expanded Delight", "expandeddelight");
            case "screenshot_viewer" -> new Translation("Screenshot Viewer", "screenshot_viewer");
            case "ragdoll_reactions" -> new Translation("Ragdoll Reactions", "ragdoll_reactions");
            case "lendersdelight" -> new Translation("L_Ender's Delight", "lendersdelight");
            case "held_item_info" -> new Translation("Held Item Info", "held_item_info");
            default -> throw new IOException("Неизвестный встроенный перевод: " + modId);
        };
    }

    private static List<String> selectedPacks(Minecraft minecraft) throws IOException {
        try {
            Field field = minecraft.options.getClass().getDeclaredField("resourcePacks");
            field.setAccessible(true);
            Object value = field.get(minecraft.options);
            if (value instanceof List<?> list) {
                @SuppressWarnings("unchecked") List<String> selected = (List<String>) list;
                return selected;
            }
            throw new IOException("Неизвестный формат списка ресурс-паков.");
        } catch (ReflectiveOperationException | SecurityException exception) {
            throw new IOException("Не удалось получить список активных ресурс-паков.", exception);
        }
    }

    private static Path packDirectory() {
        return net.neoforged.fml.loading.FMLPaths.GAMEDIR.get().resolve("resourcepacks").resolve(PACK_FOLDER);
    }

    private static Path translationFile(Translation translation) {
        return packDirectory().resolve("assets").resolve(translation.namespace()).resolve("lang").resolve("ru_ru.json");
    }

    private static void preparePack(Path pack) throws IOException {
        Files.createDirectories(pack.getParent());
        verifyOwnedPack(pack);
        Files.createDirectories(pack);
        Files.writeString(pack.resolve("pack.mcmeta"),
                "{\n  \"pack\": {\n    \"pack_format\": 34,\n"
                        + "    \"description\": \"Rusify — встроенные переводы\"\n  }\n}\n",
                StandardCharsets.UTF_8);
        Files.writeString(pack.resolve(MARKER), MARKER_CONTENT, StandardCharsets.UTF_8);
    }

    private static void verifyOwnedPack(Path pack) throws IOException {
        if (!Files.exists(pack)) return;
        Path marker = pack.resolve(MARKER);
        if (!Files.isRegularFile(marker) || !Files.readString(marker, StandardCharsets.UTF_8).equals(MARKER_CONTENT)) {
            throw new IOException("Папка " + pack.getFileName() + " не принадлежит Rusify и не будет изменена.");
        }
    }

    private static boolean hasAnyTranslation(Path pack) throws IOException {
        for (String modId : MODS) {
            Translation translation = translation(modId);
            if (Files.isRegularFile(pack.resolve("assets").resolve(translation.namespace())
                    .resolve("lang").resolve("ru_ru.json"))) return true;
        }
        return false;
    }

    private static void removeLegacyPacks(List<String> selected) throws IOException {
        Path root = net.neoforged.fml.loading.FMLPaths.GAMEDIR.get().resolve("resourcepacks");
        for (String modId : MODS) {
            Path legacy = root.resolve("Rusify-" + modId + "-Translation");
            if (deleteOwnedPack(legacy)) selected.removeIf(("file/Rusify-" + modId + "-Translation")::equals);
        }
    }

    private static boolean deleteOwnedPack(Path pack) throws IOException {
        if (!Files.exists(pack)) return false;
        Path marker = pack.resolve(MARKER);
        if (!Files.isRegularFile(marker) || !Files.readString(marker, StandardCharsets.UTF_8).equals(MARKER_CONTENT)) {
            return false;
        }
        try (var paths = Files.walk(pack)) {
            for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) Files.deleteIfExists(path);
        }
        return true;
    }

    private static void removeEmptyParents(Path directory, Path stopAt) throws IOException {
        Path current = directory;
        while (current != null && !current.equals(stopAt) && current.startsWith(stopAt)) {
            try {
                Files.delete(current);
            } catch (java.nio.file.DirectoryNotEmptyException exception) {
                break;
            }
            current = current.getParent();
        }
    }

    private record Translation(String name, String namespace, String resourceFolder) {
        private Translation(String name, String namespace) { this(name, namespace, namespace); }
    }
}
